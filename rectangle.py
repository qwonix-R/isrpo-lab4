import math


def area(a, b):
    '''
        Возвращает площадь прямоугольника со сторонами a и b

        Параметры:
            число a (float/int) - длина стороны прямоугольника
            число b (float/int) - длина стороны прямоугольника

        Возвращаемое значение:
            a * b (float/int) - площадь прямоугольника

    '''
    return a * b


def perimeter(a, b):
    '''
        Возвращает периметр прямоугольника со сторонами a и b

        Параметры:
            число a (float/int) - длина стороны прямоугольника
            число b (float/int) - длина стороны прямоугольника

        Возвращаемое значение:
            2 * (a + b) (float/int) - периметр прямоугольника

    '''
    return 2 * (a + b)