import math


def area(r):
    '''
        Возвращает площадь окружности с радиусом r

        Параметры:
            число r  (float/int) - радиус окружности

        Возвращаемое значение:
            math.pi * r * r (float) - площадь окружности

    '''
    return math.pi * r * r


def perimeter(r):
    '''
        Возвращает длину окружности с радиусом r

        Параметры:
            число r  (float/int) - радиус окружности

        Возвращаемое значение:
            2 * math.pi * r (float) - длина окружности

    '''
    return 2 * math.pi * r

